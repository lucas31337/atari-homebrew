# Usage: .\tools\gfx.ps1 [src\rainstorm_gfx.inc]
# Generates the scene graphics tables for rainstorm.asm:
#   Cloud<r>_<reg>  41-entry playfield scroll tables (offset 0 = clear sky, 40 = clouds fully in), 4 rows
#   RainPF0/1/2     32 entries: 0-15 blank, 16-31 a 20-pixel rain pattern (tiles vertically)
#   TreeInit        5 rows x 6 playfield bytes for the three trees; TreeMask: 3 trees x 6 AND-masks
#   BoltGfx         128-row lightning sprite (rows 0-86 sky band, 87-126 ground section)
#   Flame0..3       4 animation frames x 40 rows of flame sprite over the canopy
param([string]$Out = "src\rainstorm_gfx.inc")
$ErrorActionPreference = 'Stop'

# Pack 8 pixels ('X' = on) into a byte; $msbFirst means the leftmost pixel is bit 7.
function Pack([string]$px, [bool]$msbFirst) {
    $b = 0
    for ($i = 0; $i -lt $px.Length; $i++) {
        if ($px[$i] -eq 'X') { $b = $b -bor (1 -shl ($(if ($msbFirst) { 7 - $i } else { $i }))) }
    }
    $b
}
# 40-pixel row -> PF0L PF1L PF2L PF0R PF1R PF2R (PF0 uses bits 4-7, PF1 is MSB-first, PF2 LSB-first)
function PFBytes([string]$row) {
    $out = @()
    foreach ($h in $row.Substring(0, 20), $row.Substring(20, 20)) {
        $out += (Pack $h.Substring(0, 4) $false) -shl 4
        $out += Pack $h.Substring(4, 8) $true
        $out += Pack $h.Substring(12, 8) $false
    }
    $out
}
# Sprite row: 8 pixels, leftmost = bit 7
function Sprite([string]$row) { Pack $row $true }
function Emit([string]$label, [int[]]$bytes) {
    $script:lines += "; $label ($($bytes.Count) bytes)"
    for ($i = 0; $i -lt $bytes.Count; $i += 16) {
        $chunk = $bytes[$i..([math]::Min($i + 15, $bytes.Count - 1))] | ForEach-Object { '${0:X2}' -f $_ }
        $script:lines += "{0,-12}.byte {1}" -f $(if ($i -eq 0) { $label } else { '' }), ($chunk -join ',')
    }
}
function Art([string[]]$rows) { $rows | ForEach-Object { $script:lines += ";   $_" } }

$script:lines = @("; GENERATED by tools/gfx.ps1 -- do not edit by hand", "")

#--- clouds: 40-wide art, window slides in from the right ------------------
$cloudArt = @(
    '.....XXXX...........XXXXXX..............',
    '...XXXXXXXX.......XXXXXXXXXX......XXXX..',
    '..XXXXXXXXXXX....XXXXXXXXXXXX....XXXXXXX',
    '....XXXXXXX........XXXXXXXX.......XXXXX.'
)
$regs = 'PF0L', 'PF1L', 'PF2L', 'PF0R', 'PF1R', 'PF2R'
$lines += "; clouds"; Art $cloudArt
for ($r = 0; $r -lt 4; $r++) {
    $src = ('.' * 40) + $cloudArt[$r]
    $tables = @{}; foreach ($g in $regs) { $tables[$g] = @() }
    for ($o = 0; $o -le 40; $o++) {
        $b = PFBytes $src.Substring($o, 40)      # window slides right: art enters from the right edge
        for ($k = 0; $k -lt 6; $k++) { $tables[$regs[$k]] += $b[$k] }
    }
    foreach ($g in $regs) { Emit "Cloud${r}_$g" $tables[$g] }
}
$lines += ""

#--- rain: 16-row, 20-pixel tile of short streaks (repeat mode shows it twice) ---
$rain = 0..15 | ForEach-Object { ,([char[]]('.' * 20)) }
$drops = @(@(1, 0), @(6, 9), @(11, 4), @(16, 13), @(3, 7), @(9, 2), @(14, 11), @(18, 5), @(5, 14), @(12, 10))
foreach ($drop in $drops) {                     # (column, top row); 4-line streaks
    for ($k = 0; $k -lt 4; $k++) { $rain[($drop[1] + $k) % 16][$drop[0]] = 'X' }
}
$rainRows = $rain | ForEach-Object { -join $_ }
$lines += "; rain tile"; Art $rainRows
$rp = @{ PF0 = @(0) * 16; PF1 = @(0) * 16; PF2 = @(0) * 16 }
foreach ($row in $rainRows) { $b = PFBytes ($row + $row); $rp.PF0 += $b[0]; $rp.PF1 += $b[1]; $rp.PF2 += $b[2] }
Emit 'RainPF0' $rp.PF0; Emit 'RainPF1' $rp.PF1; Emit 'RainPF2' $rp.PF2
$lines += ""

#--- trees: centres at playfield columns 7, 19, 31 ---------------------------
$centres = 7, 19, 31
$treeRows = @()
foreach ($spec in @(1, 2, 2, 1, 0)) {          # half-width per row; last row is the trunk
    $row = [char[]]('.' * 40)
    foreach ($c in $centres) { for ($x = $c - $spec; $x -le $c + $spec; $x++) { $row[$x] = 'X' } }
    $treeRows += -join $row
}
$lines += "; trees (rows 0-3 canopy, row 4 trunk)"; Art $treeRows
$init = @(); foreach ($row in $treeRows) { $init += PFBytes $row }
Emit 'TreeInit' $init
$masks = @()
foreach ($c in $centres) {
    $row = [char[]]('.' * 40); for ($x = $c - 2; $x -le $c + 2; $x++) { $row[$x] = 'X' }
    $masks += (PFBytes (-join $row)) | ForEach-Object { (-bnot $_) -band 0xFF }
}
Emit 'TreeMask' $masks
$lines += ""

#--- lightning bolt: 2-pixel-wide random walk, converging on the centre at the tree top ---
$rng = [Random]::new(7); $x = 3; $bolt = @()
for ($i = 0; $i -lt 127; $i++) {
    if ($i -ge 76 -and $i -lt 87) { $x = 3 }
    else {
        $d = $rng.Next(-2, 3); if ($rng.Next(3) -eq 0) { $d = 0 }
        $x = [math]::Max(0, [math]::Min(6, $x + $d))
    }
    $bolt += (0xC0 -shr $x)
}
$bolt += 0
Emit 'BoltGfx' $bolt
$lines += ""

#--- flames: 4 frames, 28 rows of flame + 12 blank (covers the canopy rows) ---
for ($f = 0; $f -lt 4; $f++) {
    $rng = [Random]::new(100 + $f); $rows = @()
    for ($r = 0; $r -lt 28; $r++) {
        $w = [math]::Round(1 + $r * 6 / 27) + $rng.Next(-1, 2)
        $w = [math]::Max(1, [math]::Min(8, $w))
        $left = [math]::Round(4 - $w / 2) + $rng.Next(-1, 2)
        $left = [math]::Max(0, [math]::Min(8 - $w, $left))
        if ($r -lt 10 -and $rng.Next(4) -eq 0) { $rows += '........'; continue }   # flickering tips
        $row = [char[]]('........'); for ($x = $left; $x -lt $left + $w; $x++) { $row[$x] = 'X' }
        $rows += -join $row
    }
    $rows += @('........') * 12
    Emit "Flame$f" ($rows | ForEach-Object { Sprite $_ })
}

Set-Content -Path $Out -Value $lines -Encoding ascii
Write-Host "Wrote $Out"
