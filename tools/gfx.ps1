# Usage: .\tools\gfx.ps1 [src\rainstorm_gfx.inc]
# Generates the scene graphics tables for rainstorm.asm:
#   Cloud<r>_<reg>  21-entry playfield scroll tables (offset 0 = clear sky, 20 = clouds fully in), 4 rows
#   RainPF0/1/2     32 entries: 0-15 blank, 16-31 a 20-pixel rain tile (repeats vertically)
#   Trunk/Wide/Narrow/Pile <Reg|Byte>  playfield (register, byte) patterns per tree slot
#   TOWER_REG/BYTE  the wood tower at the right edge
#   DigitL/DigitR   3x5 digits, 5 bytes each, for PF1 (bits 2..0, left = bit 2) and PF2 (reversed)
#   BoltGfx         sky-band lightning sprite; BoltBand: tree-band continuation
#   Player*         6 player sprites (stand/walk x none/block/seed), 18 rows each
param([string]$Out = "src\rainstorm_gfx.inc")
$ErrorActionPreference = 'Stop'

function Pack([string]$px, [bool]$msbFirst) {
    $b = 0
    for ($i = 0; $i -lt $px.Length; $i++) {
        if ($px[$i] -eq 'X') { $b = $b -bor (1 -shl ($(if ($msbFirst) { 7 - $i } else { $i }))) }
    }
    $b
}
# 40-pixel row -> PF0L PF1L PF2L PF0R PF1R PF2R (PF0 uses bits 4-7, PF1 is MSB-first, PF2 LSB-first)
function PFBytes([string]$row) {
    $out = @()
    foreach ($h in $row.Substring(0, 20), $row.Substring(20, 20)) {
        $out += (Pack $h.Substring(0, 4) $false) -shl 4
        $out += Pack $h.Substring(4, 8) $true
        $out += Pack $h.Substring(12, 8) $false
    }
    $out
}
# columns -> up to $n (register index, byte) pairs, zero-padded
function PFPairs([int[]]$cols, [int]$n) {
    $row = [char[]]('.' * 40); foreach ($c in $cols) { $row[$c] = 'X' }
    $b = PFBytes (-join $row); $pairs = @()
    for ($i = 0; $i -lt 6; $i++) { if ($b[$i]) { $pairs += ,@($i, $b[$i]) } }
    if ($pairs.Count -gt $n) { throw "pattern spans $($pairs.Count) registers (> $n)" }
    while ($pairs.Count -lt $n) { $pairs += ,@(0, 0) }
    ,$pairs                                     # keep a single pair nested (no unrolling)
}
function Sprite([string]$row) { Pack $row $true }
# Output goes to $script:target ('main', 'bolt' or 'player'); the bolt and player files are
# included by the assembler in one page together with the Zeros table.
function Emit([string]$label, [int[]]$bytes) {
    $script:files[$script:target] += "; $label ($($bytes.Count) bytes)"
    for ($i = 0; $i -lt $bytes.Count; $i += 16) {
        $chunk = $bytes[$i..([math]::Min($i + 15, $bytes.Count - 1))] | ForEach-Object { '${0:X2}' -f $_ }
        $script:files[$script:target] += "{0,-12} .byte {1}" -f $(if ($i -eq 0) { $label } else { '' }), ($chunk -join ',')
    }
}
function Art([string[]]$rows) { $rows | ForEach-Object { $script:files[$script:target] += ";   $_" } }

$header = @("; GENERATED by tools/gfx.ps1 -- do not edit by hand", "")
$script:files = @{ main = $header; bolt = $header; player = $header }
$script:target = 'main'
# $lines below is an alias for the main file


#--- clouds: 40-wide art, window slides in from the right ------------------
$cloudArt = @(
    '.....XXXX...........XXXXXX..............',
    '...XXXXXXXX.......XXXXXXXXXX......XXXX..',
    '..XXXXXXXXXXX....XXXXXXXXXXXX....XXXXXXX',
    '....XXXXXXX........XXXXXXXX.......XXXXX.'
)
$regs = 'PF0L', 'PF1L', 'PF2L', 'PF0R', 'PF1R', 'PF2R'
$script:files.main += "; clouds"; Art $cloudArt
for ($r = 0; $r -lt 4; $r++) {
    $src = ('.' * 40) + $cloudArt[$r]
    $tables = @{}; foreach ($g in $regs) { $tables[$g] = @() }
    for ($o = 0; $o -le 20; $o++) {              # 21 offsets, 2 columns per step
        $b = PFBytes $src.Substring(2 * $o, 40)  # window slides right: art enters from the right edge
        for ($k = 0; $k -lt 6; $k++) { $tables[$regs[$k]] += $b[$k] }
    }
    foreach ($g in $regs) { Emit "Cloud${r}_$g" $tables[$g] }
}
$script:files.main += ""

#--- rain: 16-row, 20-pixel tile of short streaks (repeat mode shows it twice) ---
$rain = 0..15 | ForEach-Object { ,([char[]]('.' * 20)) }
$drops = @(@(1, 0), @(6, 9), @(11, 4), @(16, 13), @(3, 7), @(9, 2), @(14, 11), @(18, 5), @(5, 14), @(12, 10))
foreach ($drop in $drops) {                     # (column, top row); 4-line streaks
    for ($k = 0; $k -lt 4; $k++) { $rain[($drop[1] + $k) % 16][$drop[0]] = 'X' }
}
$rainRows = $rain | ForEach-Object { -join $_ }
$script:files.main += "; rain tile"; Art $rainRows
$rp = @{ PF0 = @(0) * 16; PF1 = @(0) * 16; PF2 = @(0) * 16 }
foreach ($row in $rainRows) { $b = PFBytes ($row + $row); $rp.PF0 += $b[0]; $rp.PF1 += $b[1]; $rp.PF2 += $b[2] }
Emit 'RainPF0' $rp.PF0; Emit 'RainPF1' $rp.PF1; Emit 'RainPF2' $rp.PF2
$script:files.main += ""

#--- trees, piles, tower: playfield patterns per tree slot (centres 7, 19, 31) ---
$centres = 7, 19, 31
$t = @{ TrunkReg = @(); TrunkByte = @(); WideReg = @(); WideByte = @(); NarrowReg = @(); NarrowByte = @(); PileReg = @(); PileByte = @() }
foreach ($c in $centres) {
    $p = PFPairs @($c) 1;                       $t.TrunkReg += $p[0][0];  $t.TrunkByte += $p[0][1]
    $p = PFPairs (($c - 2)..($c + 2)) 2;        foreach ($q in $p) { $t.WideReg += $q[0]; $t.WideByte += $q[1] }
    $p = PFPairs (($c - 1)..($c + 1)) 2;        foreach ($q in $p) { $t.NarrowReg += $q[0]; $t.NarrowByte += $q[1] }
    $p = PFPairs @(($c - 1), $c) 1;             $t.PileReg += $p[0][0];   $t.PileByte += $p[0][1]
}
$script:files.main += "; tree slot patterns: trunk 1 col, canopy wide 5 cols / narrow 3 cols, wood pile 2 cols"
foreach ($k in 'TrunkReg', 'TrunkByte', 'WideReg', 'WideByte', 'NarrowReg', 'NarrowByte', 'PileReg', 'PileByte') { Emit $k $t[$k] }
$p = PFPairs @(36, 37) 1
$script:files.main += ("TOWER_REG   = {0}" -f $p[0][0]), ("TOWER_BYTE  = `${0:X2}" -f $p[0][1]), ""

#--- digits 3x5 for the status line ------------------------------------------
$digits = @('XXX X.X X.X X.X XXX', '.X. XX. .X. .X. XXX', 'XXX ..X XXX X.. XXX', 'XXX ..X XXX ..X XXX', 'X.X X.X XXX ..X ..X',
            'XXX X.. XXX ..X XXX', 'XXX X.. XXX X.X XXX', 'XXX ..X ..X ..X ..X', 'XXX X.X XXX X.X XXX', 'XXX X.X XXX ..X XXX')
$dl = @(); $dr = @()
foreach ($g in $digits) { foreach ($row in ($g -split ' ')) { $dl += (Pack $row $true) -shr 5; $dr += Pack $row $false } }
Emit 'DigitL' $dl; Emit 'DigitR' $dr
$script:files.main += ""

#--- lightning bolt: 2-pixel-wide random walk ---------------------------------
$rng = [Random]::new(7); $x = 3
function Walk($n, $converge) {
    $out = @()
    for ($i = 0; $i -lt $n; $i++) {
        if ($converge -and $i -ge $n - 10) { $script:x = 3 }
        else {
            $d = $script:rng.Next(-2, 3); if ($script:rng.Next(3) -eq 0) { $d = 0 }
            $script:x = [math]::Max(0, [math]::Min(6, $script:x + $d))
        }
        $out += (0xC0 -shr $script:x)
    }
    $out
}
Emit 'BoltGfx' (Walk 79 $true)                  # sky band (SKY_LINES rows)
$script:target = 'bolt'
Emit 'BoltBand' (Walk 48 $false)                # tree band (TREE_ROWS*BLOCK_LINES rows); Zeros must follow
$script:target = 'player'

#--- player: 6 rows of carried item + 12 rows of person -----------------------
$items = @{
    None  = @('........') * 6
    Block = @('........', '.XXXXXX.', '.X.XX.X.', '.XXXXXX.', '.X.XX.X.', '.XXXXXX.')
    Seed  = @('........', '........', '...XX...', '..XXXX..', '...XX...', '........')
}
$stand = @('..XXX...', '..XXX...', '...X....', '.XXXXX..', 'X.XXX.X.', '..XXX...', '..XXX...', '..X.X...', '..X.X...', '..X.X...', '.XX.XX..', '........')
$walk  = @('..XXX...', '..XXX...', '...X....', '.XXXXX..', 'X.XXX.X.', '..XXX...', '..XXX...', '.X...X..', '.X...X..', 'XX...XX.', '........', '........')
foreach ($item in 'None', 'Block', 'Seed') {
    Emit "PlayerStand$item" (($items[$item] + $stand) | ForEach-Object { Sprite $_ })
    Emit "PlayerWalk$item"  (($items[$item] + $walk)  | ForEach-Object { Sprite $_ })
}

Set-Content -Path $Out -Value $script:files.main -Encoding ascii
Set-Content -Path ($Out -replace '_gfx\.inc$', '_bolt.inc') -Value $script:files.bolt -Encoding ascii
Set-Content -Path ($Out -replace '_gfx\.inc$', '_player.inc') -Value $script:files.player -Encoding ascii
Write-Host "Wrote $Out (+ _bolt.inc, _player.inc)"
