# Usage: .\tools\pftext.ps1 src\temporary_text.inc Title:TEMPORARY Start:START
# Renders text in a 3x5 font onto the 40-pixel asymmetric playfield and writes
# DASM tables <Label>_PF0L/_PF1L/_PF2L/_PF0R/_PF1R/_PF2R (5 bytes each, bottom row first).
# Max 40 pixels per string (3px letters + 1px gaps; a space is a 2px gap). Supported: A-Z 0-9 space.
param(
    [Parameter(Mandatory)] [string]$Out,
    [Parameter(Mandatory, ValueFromRemainingArguments)] [string[]]$Items
)
$ErrorActionPreference = 'Stop'

$font = @{
    'A'='XXX X.X XXX X.X X.X'; 'B'='XX. X.X XX. X.X XX.'; 'C'='XXX X.. X.. X.. XXX'
    'D'='XX. X.X X.X X.X XX.'; 'E'='XXX X.. XX. X.. XXX'; 'F'='XXX X.. XX. X.. X..'
    'G'='XXX X.. X.X X.X XXX'; 'H'='X.X X.X XXX X.X X.X'; 'I'='XXX .X. .X. .X. XXX'
    'J'='..X ..X ..X X.X XXX'; 'K'='X.X X.X XX. X.X X.X'; 'L'='X.. X.. X.. X.. XXX'
    'M'='X.X XXX XXX X.X X.X'; 'N'='XX. X.X X.X X.X X.X'; 'O'='XXX X.X X.X X.X XXX'
    'P'='XXX X.X XXX X.. X..'; 'Q'='XXX X.X X.X XXX ..X'; 'R'='XXX X.X XX. X.X X.X'
    'S'='XXX X.. XXX ..X XXX'; 'T'='XXX .X. .X. .X. .X.'; 'U'='X.X X.X X.X X.X XXX'
    'V'='X.X X.X X.X X.X .X.'; 'W'='X.X X.X XXX XXX X.X'; 'X'='X.X X.X .X. X.X X.X'
    'Y'='X.X X.X .X. .X. .X.'; 'Z'='XXX ..X .X. X.. XXX'
    ' '='    '   # zero-width glyph (5 empty rows): a space is just a 2-pixel gap
    '0'='XXX X.X X.X X.X XXX'; '1'='.X. XX. .X. .X. XXX'; '2'='XXX ..X XXX X.. XXX'
    '3'='XXX ..X XXX ..X XXX'; '4'='X.X X.X XXX ..X ..X'; '5'='XXX X.. XXX ..X XXX'
    '6'='XXX X.. XXX X.X XXX'; '7'='XXX ..X ..X ..X ..X'; '8'='XXX X.X XXX X.X XXX'
    '9'='XXX X.X XXX ..X XXX'
}

# Pack 8 pixels into a byte; $msbFirst means the leftmost pixel is bit 7.
function Pack([string]$px, [bool]$msbFirst) {
    $b = 0
    for ($i = 0; $i -lt $px.Length; $i++) {
        if ($px[$i] -eq 'X') { $b = $b -bor (1 -shl ($(if ($msbFirst) { 7 - $i } else { $i }))) }
    }
    $b
}

$lines = @("; GENERATED by tools/pftext.ps1 -- do not edit by hand", "")
foreach ($item in $Items) {
    $label, $text = $item -split ':', 2
    $text = $text.ToUpper()
    $rows = foreach ($r in 0..4) {
        $glyphs = foreach ($c in $text.ToCharArray()) {
            $g = $font["$c"]; if ($null -eq $g) { throw "No glyph for '$c'" }
            ($g -split ' ')[$r]
        }
        $px = $glyphs -join '.'
        if ($px.Length -gt 40) { throw "'$text' is $($px.Length) pixels wide; max is 40" }
        $pad = [math]::Floor((40 - $px.Length) / 2)
        ('.' * $pad + $px).PadRight(40, '.')
    }

    $tables = [ordered]@{ PF0L=@(); PF1L=@(); PF2L=@(); PF0R=@(); PF1R=@(); PF2R=@() }
    foreach ($row in $rows[4..0]) {   # bottom row first: kernel counts Y down
        foreach ($half in 'L','R') {
            $h = $row.Substring($(if ($half -eq 'L') { 0 } else { 20 }), 20)
            $tables["PF0$half"] += (Pack $h.Substring(0, 4) $false) -shl 4
            $tables["PF1$half"] += Pack $h.Substring(4, 8) $true
            $tables["PF2$half"] += Pack $h.Substring(12, 8) $false
        }
    }

    $lines += "; `"$text`""
    $rows | ForEach-Object { $lines += ";   $_" }
    foreach ($k in $tables.Keys) {
        $lines += "{0,-12}.byte {1}" -f "${label}_$k", (($tables[$k] | ForEach-Object { '${0:X2}' -f $_ }) -join ',')
    }
    $lines += ""
}
Set-Content -Path $Out -Value $lines -Encoding ascii
Write-Host "Wrote $Out"
